
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."GOLD_NDC_REVIEW_DASHBOARD" ("STATE", "REPORT_YEAR", "REPORT_QUARTER", "UTILIZATION_TYPE", "NDC", "PRODUCT_NAME", "PREV_RX", "REPORTED_RX", "REPORTED_UNITS", "REPORTED_REIMBURSEMENT", "SUPPRESSED_ROWS", "UNITS_PER_RX", "REIMBURSEMENT_PER_UNIT", "REIMBURSEMENT_PER_RX", "UNITS_PER_RX_CHANGE_PCT", "REIMB_PER_UNIT_CHANGE_PCT", "REIMB_PER_RX_CHANGE_PCT", "WITHIN_NDC_EFFECT", "INVESTIGATION_CATEGORY", "REVIEW_PRIORITY") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT
    Q.STATE,
    Q.REPORT_YEAR,
    Q.REPORT_QUARTER,
    Q.UTILIZATION_TYPE,
    Q.NDC,
    Q.PRODUCT_NAME,

    Q.PREV_RX,
    Q.REPORTED_RX,

    G.REPORTED_UNITS,
    G.REPORTED_REIMBURSEMENT,
    G.SUPPRESSED_ROWS,

    ROUND(G.UNITS_PER_RX, 2) AS UNITS_PER_RX,
    ROUND(G.REIMBURSEMENT_PER_UNIT, 2)
        AS REIMBURSEMENT_PER_UNIT,
    ROUND(G.REIMBURSEMENT_PER_RX, 2)
        AS REIMBURSEMENT_PER_RX,

    Q.UNITS_PER_RX_CHANGE_PCT,
    Q.REIMB_PER_UNIT_CHANGE_PCT,
    Q.REIMB_PER_RX_CHANGE_PCT,
    Q.WITHIN_NDC_EFFECT,

    Q.INVESTIGATION_CATEGORY,
    Q.REVIEW_PRIORITY

FROM GOLD_NDC_INVESTIGATION_QUEUE Q

JOIN GOLD_NDC_QUARTERLY G
  ON Q.STATE = G.STATE
 AND Q.REPORT_YEAR = G.REPORT_YEAR
 AND Q.REPORT_QUARTER = G.REPORT_QUARTER
 AND Q.UTILIZATION_TYPE = G.UTILIZATION_TYPE
 AND Q.NDC = G.NDC;
