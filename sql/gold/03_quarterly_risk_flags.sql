
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."GOLD_QUARTERLY_RISK_FLAGS" ("STATE", "REPORT_YEAR", "REPORT_QUARTER", "UTILIZATION_TYPE", "REIMBURSEMENT_PER_RX", "QOQ_COST_CHANGE_PCT", "QOQ_VOLUME_CHANGE_PCT", "SUPPRESSED_ROW_PCT", "RISK_STATUS") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT
    STATE,
    REPORT_YEAR,
    REPORT_QUARTER,
    UTILIZATION_TYPE,
    REIMBURSEMENT_PER_RX,
    QOQ_COST_CHANGE_PCT,
    QOQ_VOLUME_CHANGE_PCT,
    SUPPRESSED_ROW_PCT,

    CASE
        WHEN QOQ_COST_CHANGE_PCT >= 5
         AND QOQ_VOLUME_CHANGE_PCT < 0
        THEN 'REVIEW REQUIRED'

        ELSE 'NO TRIGGER'
    END AS RISK_STATUS

FROM GOLD_QUARTERLY_TRENDS;
