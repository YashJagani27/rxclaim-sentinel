
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."GOLD_QUARTERLY_PHARMACY_KPIS" ("STATE", "REPORT_YEAR", "REPORT_QUARTER", "UTILIZATION_TYPE", "SOURCE_ROWS", "SUPPRESSED_ROWS", "REPORTABLE_ROWS", "REPORTED_PRESCRIPTIONS", "REPORTED_UNITS", "REPORTED_REIMBURSEMENT", "REIMBURSEMENT_PER_RX", "SUPPRESSED_ROW_PCT") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT
    STATE,
    REPORT_YEAR,
    REPORT_QUARTER,
    UTILIZATION_TYPE,

    COUNT(*) AS SOURCE_ROWS,

    SUM(
        CASE WHEN IS_SUPPRESSED = 'Y'
        THEN 1 ELSE 0 END
    ) AS SUPPRESSED_ROWS,

    SUM(
        CASE WHEN IS_SUPPRESSED = 'N'
        THEN 1 ELSE 0 END
    ) AS REPORTABLE_ROWS,

    SUM(NUMBER_OF_PRESCRIPTIONS)
        AS REPORTED_PRESCRIPTIONS,

    SUM(UNITS_REIMBURSED)
        AS REPORTED_UNITS,

    ROUND(SUM(TOTAL_AMOUNT_REIMBURSED), 2)
        AS REPORTED_REIMBURSEMENT,

    ROUND(
        SUM(TOTAL_AMOUNT_REIMBURSED)
        / NULLIF(SUM(NUMBER_OF_PRESCRIPTIONS), 0),
        2
    ) AS REIMBURSEMENT_PER_RX,

    ROUND(
        100 * SUM(
            CASE WHEN IS_SUPPRESSED = 'Y'
            THEN 1 ELSE 0 END
        ) / COUNT(*),
        2
    ) AS SUPPRESSED_ROW_PCT

FROM CLEAN_MEDICAID_2025

GROUP BY
    STATE,
    REPORT_YEAR,
    REPORT_QUARTER,
    UTILIZATION_TYPE;
