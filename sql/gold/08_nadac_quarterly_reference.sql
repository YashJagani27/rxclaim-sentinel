
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."GOLD_NADAC_QUARTERLY_REFERENCE" ("NDC", "NDC_DESCRIPTION", "REPORT_YEAR", "REPORT_QUARTER", "NADAC_PER_UNIT", "PRICING_UNIT", "EFFECTIVE_DATE", "REFERENCE_DATE") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  WITH RANKED_PRICES AS (
    SELECT
        NDC,
        NDC_DESCRIPTION,

        EXTRACT(YEAR FROM AS_OF_DATE)
            AS REPORT_YEAR,

        TO_NUMBER(TO_CHAR(AS_OF_DATE, 'Q'))
            AS REPORT_QUARTER,

        NADAC_PER_UNIT,
        PRICING_UNIT,
        EFFECTIVE_DATE,
        AS_OF_DATE,

        ROW_NUMBER() OVER (
            PARTITION BY
                NDC,
                TRUNC(AS_OF_DATE, 'Q')

            ORDER BY AS_OF_DATE DESC
        ) AS RN

    FROM CLEAN_NADAC_2025

    WHERE AS_OF_DATE >= DATE '2025-01-01'
      AND AS_OF_DATE < DATE '2026-01-01'
      AND NADAC_PER_UNIT > 0
)

SELECT
    NDC,
    NDC_DESCRIPTION,
    REPORT_YEAR,
    REPORT_QUARTER,
    NADAC_PER_UNIT,
    PRICING_UNIT,
    EFFECTIVE_DATE,
    AS_OF_DATE AS REFERENCE_DATE

FROM RANKED_PRICES

WHERE RN = 1;
