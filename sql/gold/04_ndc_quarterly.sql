
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."GOLD_NDC_QUARTERLY" ("STATE", "REPORT_YEAR", "REPORT_QUARTER", "UTILIZATION_TYPE", "NDC", "PRODUCT_NAME", "SOURCE_ROWS", "SUPPRESSED_ROWS", "REPORTED_RX", "REPORTED_UNITS", "REPORTED_REIMBURSEMENT", "UNITS_PER_RX", "REIMBURSEMENT_PER_UNIT", "REIMBURSEMENT_PER_RX") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT
    STATE,
    REPORT_YEAR,
    REPORT_QUARTER,
    UTILIZATION_TYPE,
    NDC,

    MAX(PRODUCT_NAME) AS PRODUCT_NAME,

    COUNT(*) AS SOURCE_ROWS,

    SUM(
        CASE
            WHEN IS_SUPPRESSED = 'Y'
            THEN 1 ELSE 0
        END
    ) AS SUPPRESSED_ROWS,

    SUM(NUMBER_OF_PRESCRIPTIONS)
        AS REPORTED_RX,

    SUM(UNITS_REIMBURSED)
        AS REPORTED_UNITS,

    SUM(TOTAL_AMOUNT_REIMBURSED)
        AS REPORTED_REIMBURSEMENT,

    SUM(UNITS_REIMBURSED)
        / NULLIF(SUM(NUMBER_OF_PRESCRIPTIONS), 0)
        AS UNITS_PER_RX,

    SUM(TOTAL_AMOUNT_REIMBURSED)
        / NULLIF(SUM(UNITS_REIMBURSED), 0)
        AS REIMBURSEMENT_PER_UNIT,

    SUM(TOTAL_AMOUNT_REIMBURSED)
        / NULLIF(SUM(NUMBER_OF_PRESCRIPTIONS), 0)
        AS REIMBURSEMENT_PER_RX

FROM CLEAN_MEDICAID_2025

GROUP BY
    STATE,
    REPORT_YEAR,
    REPORT_QUARTER,
    UTILIZATION_TYPE,
    NDC;
