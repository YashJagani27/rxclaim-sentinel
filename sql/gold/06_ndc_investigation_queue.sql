
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."GOLD_NDC_INVESTIGATION_QUEUE" ("STATE", "REPORT_YEAR", "REPORT_QUARTER", "UTILIZATION_TYPE", "NDC", "PRODUCT_NAME", "PREV_RX", "REPORTED_RX", "UNITS_PER_RX_CHANGE_PCT", "REIMB_PER_UNIT_CHANGE_PCT", "REIMB_PER_RX_CHANGE_PCT", "WITHIN_NDC_EFFECT", "INVESTIGATION_CATEGORY", "REVIEW_PRIORITY") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT
    STATE,
    REPORT_YEAR,
    REPORT_QUARTER,
    UTILIZATION_TYPE,
    NDC,
    PRODUCT_NAME,

    PREV_RX,
    REPORTED_RX,

    UNITS_PER_RX_CHANGE_PCT,
    REIMB_PER_UNIT_CHANGE_PCT,
    REIMB_PER_RX_CHANGE_PCT,

    WITHIN_NDC_EFFECT,

    CASE
        WHEN ABS(REIMB_PER_UNIT_CHANGE_PCT) >=
             2 * ABS(UNITS_PER_RX_CHANGE_PCT)
        THEN 'UNIT_REIMBURSEMENT_DOMINANT'

        WHEN ABS(UNITS_PER_RX_CHANGE_PCT) >=
             2 * ABS(REIMB_PER_UNIT_CHANGE_PCT)
        THEN 'QUANTITY_DOMINANT'

        ELSE 'MIXED'
    END AS INVESTIGATION_CATEGORY,

    CASE
        WHEN WITHIN_NDC_EFFECT >= 500000
        THEN 'HIGH'

        WHEN WITHIN_NDC_EFFECT >= 100000
        THEN 'MEDIUM'

        ELSE 'LOW'
    END AS REVIEW_PRIORITY

FROM GOLD_NDC_QOQ_ANALYSIS

WHERE REIMB_PER_RX_CHANGE_PCT >= 20
  AND WITHIN_NDC_EFFECT > 0;
