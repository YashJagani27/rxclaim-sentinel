
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."GOLD_MEDICAID_NADAC_REFERENCE" ("STATE", "REPORT_YEAR", "REPORT_QUARTER", "UTILIZATION_TYPE", "NDC", "PRODUCT_NAME", "IS_SUPPRESSED", "NUMBER_OF_PRESCRIPTIONS", "UNITS_REIMBURSED", "TOTAL_AMOUNT_REIMBURSED", "REIMBURSEMENT_PER_RX", "REIMBURSEMENT_PER_UNIT", "NADAC_PER_UNIT", "NADAC_PRICING_UNIT", "NADAC_EFFECTIVE_DATE", "NADAC_REFERENCE_DATE", "NADAC_MATCH_STATUS") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT
    -- Medicaid identification
    M.STATE,
    M.REPORT_YEAR,
    M.REPORT_QUARTER,
    M.UTILIZATION_TYPE,
    M.NDC,
    M.PRODUCT_NAME,

    -- Medicaid utilization
    M.IS_SUPPRESSED,
    M.NUMBER_OF_PRESCRIPTIONS,
    M.UNITS_REIMBURSED,
    M.TOTAL_AMOUNT_REIMBURSED,

    -- Medicaid reimbursement metrics
    ROUND(
        M.TOTAL_AMOUNT_REIMBURSED /
        NULLIF(M.NUMBER_OF_PRESCRIPTIONS, 0),
        2
    ) AS REIMBURSEMENT_PER_RX,

    ROUND(
        M.TOTAL_AMOUNT_REIMBURSED /
        NULLIF(M.UNITS_REIMBURSED, 0),
        4
    ) AS REIMBURSEMENT_PER_UNIT,

    -- NADAC reference information
    N.NADAC_PER_UNIT,
    N.PRICING_UNIT AS NADAC_PRICING_UNIT,
    N.EFFECTIVE_DATE AS NADAC_EFFECTIVE_DATE,
    N.REFERENCE_DATE AS NADAC_REFERENCE_DATE,

    -- Reference coverage indicator
    CASE
        WHEN N.NDC IS NOT NULL
        THEN 'MATCHED'
        ELSE 'NO_REFERENCE'
    END AS NADAC_MATCH_STATUS

FROM CLEAN_MEDICAID_2025 M

LEFT JOIN GOLD_NADAC_QUARTERLY_REFERENCE N
    ON M.NDC = N.NDC
   AND M.REPORT_YEAR = N.REPORT_YEAR
   AND M.REPORT_QUARTER = N.REPORT_QUARTER;
