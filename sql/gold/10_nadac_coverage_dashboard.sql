
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."GOLD_NADAC_COVERAGE_DASHBOARD" ("STATE", "REPORT_YEAR", "REPORT_QUARTER", "UTILIZATION_TYPE", "MEDICAID_ROWS", "SUPPRESSED_ROWS", "REPORTABLE_ROWS", "MATCHED_ROWS", "UNMATCHED_ROWS", "REPORTABLE_MATCHED_ROWS", "EA_ROWS", "ML_ROWS", "GM_ROWS", "MATCH_RATE_PCT", "REPORTED_REIMBURSEMENT", "MATCHED_REPORTED_REIMBURSEMENT") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT
    STATE,
    REPORT_YEAR,
    REPORT_QUARTER,
    UTILIZATION_TYPE,

    COUNT(*) AS MEDICAID_ROWS,

    SUM(
        CASE WHEN IS_SUPPRESSED = 'Y'
        THEN 1 ELSE 0 END
    ) AS SUPPRESSED_ROWS,

    SUM(
        CASE WHEN IS_SUPPRESSED = 'N'
        THEN 1 ELSE 0 END
    ) AS REPORTABLE_ROWS,

    SUM(
        CASE WHEN NADAC_MATCH_STATUS = 'MATCHED'
        THEN 1 ELSE 0 END
    ) AS MATCHED_ROWS,

    SUM(
        CASE WHEN NADAC_MATCH_STATUS = 'NO_REFERENCE'
        THEN 1 ELSE 0 END
    ) AS UNMATCHED_ROWS,

    SUM(
        CASE
            WHEN NADAC_MATCH_STATUS = 'MATCHED'
             AND IS_SUPPRESSED = 'N'
            THEN 1 ELSE 0
        END
    ) AS REPORTABLE_MATCHED_ROWS,

    SUM(
        CASE WHEN NADAC_PRICING_UNIT = 'EA'
        THEN 1 ELSE 0 END
    ) AS EA_ROWS,

    SUM(
        CASE WHEN NADAC_PRICING_UNIT = 'ML'
        THEN 1 ELSE 0 END
    ) AS ML_ROWS,

    SUM(
        CASE WHEN NADAC_PRICING_UNIT = 'GM'
        THEN 1 ELSE 0 END
    ) AS GM_ROWS,

    ROUND(
        100 * SUM(
            CASE WHEN NADAC_MATCH_STATUS = 'MATCHED'
            THEN 1 ELSE 0 END
        ) / NULLIF(COUNT(*), 0),
        2
    ) AS MATCH_RATE_PCT,

    ROUND(
        SUM(TOTAL_AMOUNT_REIMBURSED), 2
    ) AS REPORTED_REIMBURSEMENT,

    ROUND(
        SUM(
            CASE
                WHEN NADAC_MATCH_STATUS = 'MATCHED'
                THEN TOTAL_AMOUNT_REIMBURSED
            END
        ), 2
    ) AS MATCHED_REPORTED_REIMBURSEMENT

FROM GOLD_MEDICAID_NADAC_REFERENCE

GROUP BY
    STATE,
    REPORT_YEAR,
    REPORT_QUARTER,
    UTILIZATION_TYPE;
