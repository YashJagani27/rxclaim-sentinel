
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."GOLD_QUARTERLY_TRENDS" ("STATE", "REPORT_YEAR", "REPORT_QUARTER", "UTILIZATION_TYPE", "REPORTED_PRESCRIPTIONS", "REPORTED_REIMBURSEMENT", "REIMBURSEMENT_PER_RX", "SUPPRESSED_ROW_PCT", "QOQ_COST_CHANGE_PCT", "QOQ_VOLUME_CHANGE_PCT") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  WITH QUARTERLY_DATA AS (
    SELECT
        STATE,
        REPORT_YEAR,
        REPORT_QUARTER,
        UTILIZATION_TYPE,
        REPORTED_PRESCRIPTIONS,
        REPORTED_REIMBURSEMENT,
        REIMBURSEMENT_PER_RX,
        SUPPRESSED_ROW_PCT,

        LAG(REIMBURSEMENT_PER_RX) OVER (
            PARTITION BY STATE, UTILIZATION_TYPE
            ORDER BY REPORT_YEAR, REPORT_QUARTER
        ) AS PREV_COST_PER_RX,

        LAG(REPORTED_PRESCRIPTIONS) OVER (
            PARTITION BY STATE, UTILIZATION_TYPE
            ORDER BY REPORT_YEAR, REPORT_QUARTER
        ) AS PREV_PRESCRIPTIONS

    FROM GOLD_QUARTERLY_PHARMACY_KPIS
)
SELECT
    STATE,
    REPORT_YEAR,
    REPORT_QUARTER,
    UTILIZATION_TYPE,
    REPORTED_PRESCRIPTIONS,
    REPORTED_REIMBURSEMENT,
    REIMBURSEMENT_PER_RX,
    SUPPRESSED_ROW_PCT,

    ROUND(
        100 * (
            REIMBURSEMENT_PER_RX - PREV_COST_PER_RX
        ) / NULLIF(PREV_COST_PER_RX, 0),
        2
    ) AS QOQ_COST_CHANGE_PCT,

    ROUND(
        100 * (
            REPORTED_PRESCRIPTIONS - PREV_PRESCRIPTIONS
        ) / NULLIF(PREV_PRESCRIPTIONS, 0),
        2
    ) AS QOQ_VOLUME_CHANGE_PCT

FROM QUARTERLY_DATA;
