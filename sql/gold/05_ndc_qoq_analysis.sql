
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."GOLD_NDC_QOQ_ANALYSIS" ("STATE", "REPORT_YEAR", "REPORT_QUARTER", "UTILIZATION_TYPE", "NDC", "PRODUCT_NAME", "PREV_RX", "REPORTED_RX", "UNITS_PER_RX_CHANGE_PCT", "REIMB_PER_UNIT_CHANGE_PCT", "REIMB_PER_RX_CHANGE_PCT", "WITHIN_NDC_EFFECT") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  WITH HISTORY AS (
    SELECT
        STATE,
        REPORT_YEAR,
        REPORT_QUARTER,
        UTILIZATION_TYPE,
        NDC,
        PRODUCT_NAME,
        SUPPRESSED_ROWS,
        REPORTED_RX,
        UNITS_PER_RX,
        REIMBURSEMENT_PER_UNIT,
        REIMBURSEMENT_PER_RX,

        LAG(REPORT_YEAR) OVER (
            PARTITION BY STATE, UTILIZATION_TYPE, NDC
            ORDER BY REPORT_YEAR, REPORT_QUARTER
        ) AS PREV_YEAR,

        LAG(REPORT_QUARTER) OVER (
            PARTITION BY STATE, UTILIZATION_TYPE, NDC
            ORDER BY REPORT_YEAR, REPORT_QUARTER
        ) AS PREV_QUARTER,

        LAG(SUPPRESSED_ROWS) OVER (
            PARTITION BY STATE, UTILIZATION_TYPE, NDC
            ORDER BY REPORT_YEAR, REPORT_QUARTER
        ) AS PREV_SUPPRESSED,

        LAG(REPORTED_RX) OVER (
            PARTITION BY STATE, UTILIZATION_TYPE, NDC
            ORDER BY REPORT_YEAR, REPORT_QUARTER
        ) AS PREV_RX,

        LAG(UNITS_PER_RX) OVER (
            PARTITION BY STATE, UTILIZATION_TYPE, NDC
            ORDER BY REPORT_YEAR, REPORT_QUARTER
        ) AS PREV_UNITS_PER_RX,

        LAG(REIMBURSEMENT_PER_UNIT) OVER (
            PARTITION BY STATE, UTILIZATION_TYPE, NDC
            ORDER BY REPORT_YEAR, REPORT_QUARTER
        ) AS PREV_REIMB_PER_UNIT,

        LAG(REIMBURSEMENT_PER_RX) OVER (
            PARTITION BY STATE, UTILIZATION_TYPE, NDC
            ORDER BY REPORT_YEAR, REPORT_QUARTER
        ) AS PREV_REIMB_PER_RX

    FROM GOLD_NDC_QUARTERLY
)

SELECT
    STATE,
    REPORT_YEAR,
    REPORT_QUARTER,
    UTILIZATION_TYPE,
    NDC,
    PRODUCT_NAME,

    PREV_RX,
    REPORTED_RX,

    ROUND(
        100 * (UNITS_PER_RX /
        NULLIF(PREV_UNITS_PER_RX, 0) - 1), 2
    ) AS UNITS_PER_RX_CHANGE_PCT,

    ROUND(
        100 * (REIMBURSEMENT_PER_UNIT /
        NULLIF(PREV_REIMB_PER_UNIT, 0) - 1), 2
    ) AS REIMB_PER_UNIT_CHANGE_PCT,

    ROUND(
        100 * (REIMBURSEMENT_PER_RX /
        NULLIF(PREV_REIMB_PER_RX, 0) - 1), 2
    ) AS REIMB_PER_RX_CHANGE_PCT,

    ROUND(
        REPORTED_RX *
        (REIMBURSEMENT_PER_RX - PREV_REIMB_PER_RX),
        2
    ) AS WITHIN_NDC_EFFECT

FROM HISTORY

WHERE
    REPORT_YEAR * 4 + REPORT_QUARTER =
    PREV_YEAR * 4 + PREV_QUARTER + 1

    AND SUPPRESSED_ROWS = 0
    AND PREV_SUPPRESSED = 0

    AND REPORTED_RX >= 30
    AND PREV_RX >= 30

    AND REIMBURSEMENT_PER_RX > 0
    AND PREV_REIMB_PER_RX > 0
    AND UNITS_PER_RX > 0
    AND PREV_UNITS_PER_RX > 0
    AND REIMBURSEMENT_PER_UNIT > 0
    AND PREV_REIMB_PER_UNIT > 0;
