
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."CLEAN_NADAC_2025" ("NDC", "NDC_DESCRIPTION", "NADAC_PER_UNIT", "PRICING_UNIT", "EFFECTIVE_DATE", "AS_OF_DATE", "PHARMACY_TYPE_INDICATOR", "OTC", "EXPLANATION_CODE", "SOURCE_FILE", "UPDATED_TIMESTAMP") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT
    -- Drug identification
    TRIM(NDC) AS NDC,
    TRIM(NDC_DESCRIPTION) AS NDC_DESCRIPTION,

    -- NADAC reference price
    TO_NUMBER(
        TRIM(NADAC_PER_UNIT)
        DEFAULT NULL ON CONVERSION ERROR
    ) AS NADAC_PER_UNIT,

    UPPER(TRIM(PRICING_UNIT)) AS PRICING_UNIT,

    -- Historical pricing dates
    TO_DATE(
        TRIM(EFFECTIVE_DATE)
        DEFAULT NULL ON CONVERSION ERROR,
        'MM/DD/YYYY'
    ) AS EFFECTIVE_DATE,

    TO_DATE(
        TRIM(AS_OF_DATE)
        DEFAULT NULL ON CONVERSION ERROR,
        'MM/DD/YYYY'
    ) AS AS_OF_DATE,

    -- Drug classification
    TRIM(PHARMACY_TYPE_INDICATOR)
        AS PHARMACY_TYPE_INDICATOR,

    TRIM(OTC) AS OTC,

    TRIM(EXPLANATION_CODE) AS EXPLANATION_CODE,

    -- Ingestion metadata
    FILENAME AS SOURCE_FILE,
    UPDATED_TIMESTAMP

FROM RAW_NADAC_2025;
