
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "ADMIN"."CLEAN_MEDICAID_2025" ("STATE", "UTILIZATION_TYPE", "NDC", "LABELER_CODE", "PRODUCT_CODE", "PACKAGE_SIZE", "REPORT_YEAR", "REPORT_QUARTER", "IS_SUPPRESSED", "PRODUCT_NAME", "UNITS_REIMBURSED", "NUMBER_OF_PRESCRIPTIONS", "TOTAL_AMOUNT_REIMBURSED", "MEDICAID_AMOUNT_REIMBURSED", "NON_MEDICAID_AMOUNT_REIMBURSED") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT
    UPPER(TRIM(STATE)) AS STATE,
    UPPER(TRIM(UTILIZATION_TYPE)) AS UTILIZATION_TYPE,

    TRIM(NDC) AS NDC,
    TRIM(LABELER_CODE) AS LABELER_CODE,
    TRIM(PRODUCT_CODE) AS PRODUCT_CODE,
    TRIM(PACKAGE_SIZE) AS PACKAGE_SIZE,

    TO_NUMBER(TRIM(YEAR)
        DEFAULT NULL ON CONVERSION ERROR) AS REPORT_YEAR,

    TO_NUMBER(TRIM(QUARTER)
        DEFAULT NULL ON CONVERSION ERROR) AS REPORT_QUARTER,

    CASE
        WHEN LOWER(TRIM(SUPPRESSION_USED)) = 'true'
        THEN 'Y'
        ELSE 'N'
    END AS IS_SUPPRESSED,

    TRIM(PRODUCT_NAME) AS PRODUCT_NAME,

    CASE WHEN LOWER(TRIM(SUPPRESSION_USED)) = 'false'
        THEN TO_NUMBER(TRIM(UNITS_REIMBURSED)
            DEFAULT NULL ON CONVERSION ERROR)
    END AS UNITS_REIMBURSED,

    CASE WHEN LOWER(TRIM(SUPPRESSION_USED)) = 'false'
        THEN TO_NUMBER(TRIM(NUMBER_OF_PRESCRIPTIONS)
            DEFAULT NULL ON CONVERSION ERROR)
    END AS NUMBER_OF_PRESCRIPTIONS,

    CASE WHEN LOWER(TRIM(SUPPRESSION_USED)) = 'false'
        THEN TO_NUMBER(TRIM(TOTAL_AMOUNT_REIMBURSED)
            DEFAULT NULL ON CONVERSION ERROR)
    END AS TOTAL_AMOUNT_REIMBURSED,

    CASE WHEN LOWER(TRIM(SUPPRESSION_USED)) = 'false'
        THEN TO_NUMBER(TRIM(MEDICAID_AMOUNT_REIMBURSED)
            DEFAULT NULL ON CONVERSION ERROR)
    END AS MEDICAID_AMOUNT_REIMBURSED,

    CASE WHEN LOWER(TRIM(SUPPRESSION_USED)) = 'false'
        THEN TO_NUMBER(TRIM(NON_MEDICAID_AMOUNT_REIMBURSED)
            DEFAULT NULL ON CONVERSION ERROR)
    END AS NON_MEDICAID_AMOUNT_REIMBURSED

FROM RAW_MEDICAID_2025;
